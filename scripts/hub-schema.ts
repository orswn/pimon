// Writes the hub link protocol as one JSON Schema document. `--check` exits 1 when the committed file differs.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import * as S from "../src/hub/protocol.schema.ts";
import { HUB_PROTOCOL } from "../src/hub/protocol.ts";
import { type EventSpec, HUB_EVENTS, HUB_ROUTES, type RouteSpec, type SchemaName } from "../src/hub/routes.ts";

const repo = join(import.meta.dirname, "..");
export const SCHEMA_FILE = join(repo, "schema", `hub-protocol-v${HUB_PROTOCOL}.json`);
const PRINT_WIDTH = 120;
const TAB_WIDTH = 2;

type Json = null | boolean | number | string | Json[] | { [key: string]: Json };

const SCHEMAS = S as unknown as Record<SchemaName, { title?: string; description?: string }>;

function ref(name: SchemaName): { $ref: string } {
	return { $ref: `#/$defs/${name}` };
}

function isSchemaName(value: unknown): value is SchemaName {
	return typeof value === "string" && Object.hasOwn(SCHEMAS, value);
}

/** A nested schema with the title of a definition becomes a `$ref` to it. */
function withRefs(node: Json, root: boolean): Json {
	if (Array.isArray(node)) return node.map((item) => withRefs(item, false));
	if (node === null || typeof node !== "object") return node;
	const title = node["title"];
	if (!root && isSchemaName(title)) {
		const out: { [key: string]: Json } = ref(title);
		const description = node["description"];
		if (description !== undefined && description !== SCHEMAS[title].description) out["description"] = description;
		return out;
	}
	const out: { [key: string]: Json } = {};
	for (const key of ["title", "description"]) if (node[key] !== undefined) out[key] = node[key];
	for (const [key, value] of Object.entries(node)) if (!(key in out)) out[key] = withRefs(value, false);
	return out;
}

function definitions(): { [key: string]: Json } {
	const defs: { [key: string]: Json } = {};
	for (const name of (Object.keys(SCHEMAS) as SchemaName[]).sort()) {
		defs[name] = withRefs(JSON.parse(JSON.stringify(SCHEMAS[name])) as Json, true);
	}
	return defs;
}

function route(key: string, spec: RouteSpec): Json {
	const [method = "", path = ""] = key.split(" ");
	const errors: { [key: string]: Json } = {};
	for (const [status, name] of Object.entries(spec.errors)) if (name) errors[status] = ref(name);
	return {
		method,
		path,
		principal: spec.principal,
		request: spec.request ? ref(spec.request) : null,
		query: (spec.query ?? {}) as Json,
		headers: (spec.headers ?? {}) as Json,
		response: spec.response === "stream" ? null : ref(spec.response),
		stream: spec.response === "stream",
		errors,
	};
}

function event(spec: EventSpec): Json {
	return { payload: ref(spec.payload), stored: spec.stored };
}

function hubSchema(): Json {
	const routes: { [key: string]: Json } = {};
	for (const [key, spec] of Object.entries(HUB_ROUTES)) routes[key] = route(key, spec);
	const events: { [key: string]: Json } = {};
	for (const [name, spec] of Object.entries(HUB_EVENTS)) events[name] = event(spec);
	return {
		$schema: "https://json-schema.org/draft/2020-12/schema",
		$id: `urn:a2a-hub:protocol:${HUB_PROTOCOL}`,
		title: `Hub link protocol ${HUB_PROTOCOL}`,
		description:
			'Generated by scripts/hub-schema.ts. Objects are open: a reader must ignore unknown fields. `x-routes` lists the link API. `x-events` lists the events of `GET /link/:agent/events`. An error body is `{ error, ...details }`. Rules for every route: each JSON response has exactly `Content-Type: application/json`. An unknown path or a wrong method gives 404 `{ "error": "not found" }`, never 405. A malformed percent escape in the path gives 400. An unexpected failure gives 500 `{ "error": "internal error" }`.',
		$defs: definitions(),
		"x-routes": routes,
		"x-events": events,
	};
}

function isScalar(value: Json): boolean {
	return value === null || typeof value !== "object";
}

/** Prints the layout that `vp fmt` gives, so the file passes the format check unchanged. */
function print(value: Json, depth: number, prefix: number, suffix: number): string {
	if (isScalar(value)) return JSON.stringify(value);
	const pad = "\t".repeat(depth + 1);
	const end = "\t".repeat(depth);
	if (Array.isArray(value)) {
		if (value.length === 0) return "[]";
		if (value.every(isScalar)) {
			const flat = `[${value.map((item) => JSON.stringify(item)).join(", ")}]`;
			if (depth * TAB_WIDTH + prefix + flat.length + suffix <= PRINT_WIDTH) return flat;
		}
		return `[\n${value.map((item, index) => pad + print(item, depth + 1, 0, index < value.length - 1 ? 1 : 0)).join(",\n")}\n${end}]`;
	}
	const entries = Object.entries(value as { [key: string]: Json });
	if (entries.length === 0) return "{}";
	const lines = entries.map(([key, item], index) => {
		const label = `${JSON.stringify(key)}: `;
		return pad + label + print(item, depth + 1, label.length, index < entries.length - 1 ? 1 : 0);
	});
	return `{\n${lines.join(",\n")}\n${end}}`;
}

export function renderHubSchema(): string {
	return `${print(hubSchema(), 0, 0, 0)}\n`;
}

if (process.argv[1] === import.meta.filename) {
	const text = renderHubSchema();
	const name = relative(process.cwd(), SCHEMA_FILE);
	if (process.argv.includes("--check")) {
		let current = "";
		try {
			current = readFileSync(SCHEMA_FILE, "utf8");
		} catch {
			// A missing file counts as a difference.
		}
		if (current !== text) {
			process.stderr.write(`${name} is out of date. Run: npm run schema\n`);
			process.exit(1);
		}
	} else {
		mkdirSync(dirname(SCHEMA_FILE), { recursive: true });
		writeFileSync(SCHEMA_FILE, text);
		process.stdout.write(`wrote ${name}\n`);
	}
}
